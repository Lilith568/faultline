"""Export a verified, minimized counterexample as a Playwright Test spec and a replayable JSON."""
from __future__ import annotations

import json
import re

from .vocab import describe_experiment

js = json.dumps  # JSON string literals (ASCII-escaped) are valid JavaScript string literals
_LINE_BREAKS = re.compile(r"[\x00-\x1f\x7f-\x9f\N{LINE SEPARATOR}\N{PARAGRAPH SEPARATOR}]+")


def _comment(text: str) -> str:
    """Text that is safe inside a // comment: no line terminators, no control characters."""
    return _LINE_BREAKS.sub(" ", str(text)).strip()


def _locator_ts(spec: dict) -> str:
    by, value = spec["by"], spec["value"]
    if by == "testid":
        return f"page.getByTestId({js(value)})"
    if by == "role":
        return f"page.getByRole({js(spec['role'])}, {{ name: {js(value)}, exact: true, includeHidden: true }})"
    if by == "label":
        return f"page.getByLabel({js(value)}, {{ exact: true }})"
    if by == "placeholder":
        return f"page.getByPlaceholder({js(value)}, {{ exact: true }})"
    return f"page.getByText({js(value)}, {{ exact: true }})"


def _match_ts(endpoint: str) -> str:
    method, path = endpoint.split()
    checks = []
    if method != "*":
        checks.append(f"r.method === {js(method)}")
    if path != "*":
        checks.append(f"r.path === {js(path)}")
    return " && ".join(checks) or "true"


def to_playwright_spec(cx: dict, url: str) -> str:
    exp = cx["experiment"]
    elements = cx["elements"]
    loc = lambda ref: _locator_ts(elements[ref]["locator"])  # noqa: E731
    text = describe_experiment(exp, {"elements": list(elements.values())})
    lines = [
        "// Generated by Faultline from a verified, minimized counterexample.",
        f"// {_comment(cx['title'])}",
        f"// Attribution: {_comment(cx['attribution'])}",
        "// This test asserts the CORRECT behaviour: it fails while the bug exists and passes once it is fixed.",
        "import { test, expect } from '@playwright/test';",
        "test.use({ serviceWorkers: 'block' });",
        "",
        f"const TARGET = process.env.FAULTLINE_TARGET ?? {js(url)};",
        "",
        f"test({js('faultline: ' + cx['title'])}, async ({{ page }}) => {{",
        "  const origin = new URL(TARGET).origin;",
        "  const requests: { method: string; path: string }[] = [];",
        "  const pageErrors: string[] = [];",
        "  const isApi = (req: any) => ['fetch', 'xhr'].includes(req.resourceType()) && new URL(req.url()).origin === origin;",
        "  page.on('request', (req) => { if (isApi(req)) requests.push({ method: req.method(), path: new URL(req.url()).pathname }); });",
        "  page.on('pageerror', (error) => pageErrors.push(String(error)));",
    ]
    if exp["perturbations"]:
        lines.append(f"  const seen = {js([0] * len(exp['perturbations']))};")
        lines.append("  await page.route((u) => u.origin === origin, async (route) => {")
        lines.append("    const req = route.request();")
        lines.append("    if (!isApi(req)) return route.continue();")
        lines.append("    const r = { method: req.method(), path: new URL(req.url()).pathname };")
        for i, p in enumerate(exp["perturbations"]):
            lines.append(f"    // {_comment(text['perturbations'][i])}")
            lines.append(f"    if ({_match_ts(p['endpoint'])}) {{")
            lines.append(f"      seen[{i}] += 1;")
            cond = "true" if p["nth"] == 0 else f"seen[{i}] === {p['nth']}"
            if p["kind"] == "delay":
                lines.append(f"      if ({cond}) await new Promise((resolve) => setTimeout(resolve, {p['ms']}));")
            else:
                lines.append(f"      if ({cond}) return route.fulfill({{ status: {p['status']}, "
                             "contentType: 'application/json', body: '{\"error\":\"injected by Faultline\"}' });")
            lines.append("    }")
        lines.append("    return route.continue();")
        lines.append("  });")
    lines.append("  await page.goto(TARGET);")
    lines.append("  await page.waitForTimeout(250);")
    for step, description in zip(exp["steps"], text["steps"]):
        action = step["action"]
        lines.append(f"  // {_comment(description)}")
        if action == "click":
            lines.append(f"  await {loc(step['ref'])}.click();")
        elif action == "dblclick":
            lines.append(f"  await {loc(step['ref'])}.dblclick();")
        elif action == "fill":
            lines.append(f"  if (await {loc(step['ref'])}.evaluate(el => el instanceof HTMLInputElement && el.type === 'password')) throw new Error('Refusing to type into a password field');")
            lines.append(f"  await {loc(step['ref'])}.fill({js(step['value'])});")
        elif action == "type":
            lines.append(f"  if (await {loc(step['ref'])}.evaluate(el => el instanceof HTMLInputElement && el.type === 'password')) throw new Error('Refusing to type into a password field');")
            lines.append(f"  await {loc(step['ref'])}.pressSequentially({js(step['value'])}, {{ delay: 120 }});")
        elif action == "press":
            lines.append(f"  await page.keyboard.press({js(step['key'])});")
        elif action == "wait":
            lines.append(f"  await page.waitForTimeout({step['ms']});")
        elif action == "reload":
            lines.append("  await page.reload();")
        if action != "wait":
            lines.append("  await page.waitForTimeout(120); // human-like pacing, same as Faultline's executor")
    lines.append("  await page.waitForTimeout(450);")
    for inv, description in zip(exp["invariants"], text["invariants"]):
        kind = inv["kind"]
        lines.append(f"  // Invariant: {_comment(description)}")
        if kind == "value_equals":
            element = elements[inv["ref"]]
            matcher = "toHaveValue" if element.get("tag") in ("input", "textarea", "select") else "toHaveText"
            lines.append(f"  await expect({loc(inv['ref'])}).{matcher}({js(inv['value'])}, {{ timeout: 1000 }});")
        elif kind == "text_contains":
            target = "page.locator('body')" if inv["ref"] == "page" else loc(inv["ref"])
            lines.append(f"  await expect({target}).toContainText({js(inv['value'])}, {{ timeout: 1000 }});")
        elif kind == "focus_returns":
            lines.append(f"  await expect({loc(inv['ref'])}).toBeFocused({{ timeout: 1000 }});")
        elif kind == "max_requests":
            lines.append(f"  expect(requests.filter((r) => {_match_ts(inv['endpoint'])}).length).toBeLessThanOrEqual({inv['max']});")
        elif kind == "no_page_errors":
            lines.append("  expect(pageErrors).toEqual([]);")
    lines.append("});")
    return "\n".join(lines) + "\n"


def to_repro(cx: dict, url: str) -> dict:
    """Self-contained repro that `faultline replay` can run without rediscovery."""
    return {"faultline_repro": 1, "title": cx["title"], "url": url, "fault_class": cx["fault_class"],
            "experiment": cx["experiment"], "elements": cx["elements"], "attribution": cx["attribution"]}


def spec_filename(cx: dict) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", cx["title"].lower()).strip("-")[:50] or "counterexample"
    return f"faultline-{slug}.spec.ts"
